from __future__ import annotations

import re
import shlex
import uuid
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

import asyncssh

from nervus import certs, plainfile
from nervus.certs import CertificateAuthority

TRUNCATE_BYTES = 32 * 1024

_TILDE_PREFIX = re.compile(r"^(~[A-Za-z0-9._-]*)(?:/(.*))?$")


def cd_target(cwd: str) -> str:
    """Render `cwd` as a shell word that `cd` will accept, tildes included.

    shlex.quote() on its own is wrong here, and was the cause of defect C
    (see procedures/003-onboard-agent-account.md). Quoting a tilde
    suppresses tilde expansion, so `cd '~'` looks for a literal directory
    named `~` and fails. `~` is the default cwd for both exec and exec_bg,
    so every call that did not pass an explicit path exited 97 having run
    nothing.

    Quoting only the tail is not sufficient either: bash expands a tilde
    only when the slash ending the tilde-prefix is itself unquoted, so
    `~'/sub'` fails exactly as `'~'` does. That was verified against real
    bash rather than reasoned about, because the first attempted fix here
    used that form and would have replaced one silent failure with
    another.

    The tilde-prefix and the slash after it are therefore emitted
    unquoted so the remote shell expands them, and everything beyond is
    quoted as normal so spaces and metacharacters in a path stay inert.
    The prefix is matched against a restricted character set, so nothing
    that could alter the command survives unquoted.
    """
    match = _TILDE_PREFIX.match(cwd)
    if match is None:
        return shlex.quote(cwd)
    prefix, rest = match.group(1), match.group(2)
    if rest is None:
        return prefix
    return f"{prefix}/{shlex.quote(rest)}"


@dataclass(frozen=True)
class ExecResult:
    run_id: str
    exit_code: int | None
    output: str
    total_bytes: int
    truncated: bool
    remote_output_path: str
    timed_out: bool


def label_line(label: str | None) -> str:
    """ADR-0025 decision 2: the line that writes the client and the run into the
    machine's journal beside the command's own lines, tagged `nervus`.

    A convenience, not evidence: anything the command runs can write the same
    words, and a client with sudo can edit the journal after. The certificate's
    login line is the one that counts. So it never stands in the command's way:
    a machine without `logger`, or a sandbox it cannot log from, runs the
    command just the same, and nothing of it reaches the output.
    """
    if label is None:
        return ""
    return f"logger -t nervus -- {shlex.quote(label)} >/dev/null 2>&1 || true\n"


def build_exec_script(run_id: str, cwd: str, command: str, label: str | None = None) -> tuple[str, str]:
    """Wrap a user command so its full output lands on the target disk.

    The remote side always gets the complete output under
    $HOME/.nervus/runs/<run_id>/ via tee, independent of whatever nervus
    itself decides to bound for the tool response. `set -o pipefail`
    plus running the whole thing through one bash invocation (not `sh`)
    is what makes `$?` after the pipe reflect the user command's exit
    status rather than tee's.

    $HOME is used unquoted rather than `~`, and left unquoted rather than
    shlex.quote()'d: quoting `~/...` disables tilde expansion entirely
    (mkdir/tee would then operate on a literal directory named `~`,
    resolved against whatever directory is current *when each line
    runs* -- wrong the moment `cd` has already changed it). run_id is
    generated by this module as a uuid4, never user input, so leaving it
    unquoted carries no injection risk.

    remote_output_path is therefore a shell-relative expression
    ("$HOME/..."), meant for a later exec/cat on the same account -- not
    a literal filesystem path an SFTP client could use as-is.
    """
    remote_dir = f"$HOME/.nervus/runs/{run_id}"
    output_path = f"{remote_dir}/output"
    exit_path = f"{remote_dir}/exit"
    cd_failed = shlex.quote(f"nervus: cannot change to working directory: {cwd}")
    script = (
        label_line(label)
        + "set -o pipefail\n"
        f"mkdir -p {remote_dir}\n"
        f"cd {cd_target(cwd)} || {{ echo {cd_failed} | tee {output_path}; exit 97; }}\n"
        "{\n"
        f"{command}\n"
        "} 2>&1 | tee " + output_path + "\n"
        "ec=$?\n"
        f'echo "$ec" > {exit_path}\n'
        'exit "$ec"\n'
    )
    return script, output_path


def bound_output(output: str, limit: int = TRUNCATE_BYTES) -> tuple[str, int, bool]:
    """Keep only the last `limit` bytes of output, with an explicit marker if trimmed."""
    data = output.encode("utf-8", errors="surrogateescape")
    total = len(data)
    if total <= limit:
        return output, total, False
    tail = data[-limit:]
    text = tail.decode("utf-8", errors="replace")
    marker = f"[... truncated, showing last {limit} of {total} bytes ...]\n"
    return marker + text, total, True


def _read_key(key: str | Path | asyncssh.SSHKey) -> asyncssh.SSHKey:
    """nervus's key, read by nervus. Given the key's name, the SSH library opens it
    itself, in a thread of its own, and waits there for ever on a pipe put at
    the name: that call never ends, and each one keeps a thread (nervus.plainfile)."""
    return asyncssh.import_private_key(plainfile.read_bytes(key)) if isinstance(key, (str, Path)) else key


async def connect(
    *,
    address: str,
    port: int = 22,
    username: str,
    client_keys: Sequence[str | Path],
    known_hosts: str | Path | asyncssh.SSHKnownHosts,
    connect_timeout: float | None = None,
    authority: CertificateAuthority | None = None,
) -> asyncssh.SSHClientConnection:
    """Open the one connection nervus is allowed to make: as `username`, with the
    single pinned key, against a known_hosts file with strict checking.

    Passing known_hosts (a path, or for an enrolled VM the keys its guest agent
    reported, ADR-0022 3a; never None) is what makes checking strict: asyncssh
    rejects any host key not already present in it.

    config=None and agent_path=None are what make "the single pinned key" true.
    asyncssh's defaults read the running account's ~/.ssh/config (a ProxyCommand
    or Host entry there changes where nervus connects, and runs a command to do
    it) and offer every key in the agent named by SSH_AUTH_SOCK or the config's
    IdentityAgent. Neither may shape a nervus connection; only the arguments do.

    Made for a client's call (certs.acting_for), with nervus's CA as
    `authority`, the key is offered first with a certificate naming the call,
    then plain, for a machine not yet moved to the CA (ADR-0025 question 1a).
    Either way the call notes the local port, which the machine's journal
    line carries too (decision 3).

    A machine whose clock is further from nervus's than the certificate's
    window refuses it as it would a wrong key, and asyncssh says only
    "Permission denied". When a certificate was offered, the refusal says
    that a clock is one cause (procedure 042, finding 1).
    """
    caller = certs.current()
    keys: list = [_read_key(k) for k in client_keys]
    signed = authority is not None and caller is not None
    if signed:
        keys = [(k, authority.sign(k, username, caller)) for k in keys] + keys
    if not isinstance(known_hosts, asyncssh.SSHKnownHosts):
        # Read here and now, as the key is: the library reads a name once a machine has answered.
        known_hosts = asyncssh.import_known_hosts(plainfile.read_text(known_hosts))
    try:
        conn = await asyncssh.connect(
            address,
            port,
            username=username,
            client_keys=keys,
            known_hosts=known_hosts,
            connect_timeout=connect_timeout,
            config=None,
            agent_path=None,
        )
    except asyncssh.PermissionDenied as exc:
        if not signed:
            raise
        raise asyncssh.PermissionDenied(
            f"{exc.reason}. nervus offered a certificate valid {certs.WINDOW_SECONDS // 60} minutes either side "
            f"of its own clock; one cause is a clock on {address} further than that from nervus's") from exc
    if caller is not None:
        sockname = conn.get_extra_info("sockname")
        if sockname:
            caller.ports.append(sockname[1])
    return conn


async def exec_command(
    conn: asyncssh.SSHClientConnection,
    *,
    cwd: str,
    command: str,
    timeout: float | None,
    run_id: str | None = None,
    label: str | None = None,
) -> ExecResult:
    """Run `command` on the target and return its bounded output plus exit code.

    On timeout, asyncssh raises TimeoutError carrying whatever partial
    output it had already collected; that partial output is still bounded
    and returned, with exit_code=None and timed_out=True so the caller
    can tell a real exit apart from one that never happened.
    """
    run_id = run_id or str(uuid.uuid4())
    script, output_path = build_exec_script(run_id, cwd, command, label)

    try:
        completed = await conn.run("bash -s", input=script, timeout=timeout)
        output, total, truncated = bound_output(completed.stdout or "")
        return ExecResult(
            run_id=run_id,
            exit_code=completed.exit_status,
            output=output,
            total_bytes=total,
            truncated=truncated,
            remote_output_path=output_path,
            timed_out=False,
        )
    except asyncssh.TimeoutError as exc:
        output, total, truncated = bound_output(exc.stdout or "")
        return ExecResult(
            run_id=run_id,
            exit_code=None,
            output=output,
            total_bytes=total,
            truncated=truncated,
            remote_output_path=output_path,
            timed_out=True,
        )
